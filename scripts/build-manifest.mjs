// Reads data/catalog.json + every topics/<slug>.html and writes assets/js/manifest.js.
// Run after adding or editing a topic page:  node scripts/build-manifest.mjs
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const catalog = JSON.parse(readFileSync(join(root, "data/catalog.json"), "utf8"));

const attr = (tag, name) => {
  const m = tag.match(new RegExp(`\\s${name}="([^"]*)"`));
  return m ? m[1] : null;
};

let problems = 0;
for (const exam of catalog.exams) {
  for (const topic of exam.topics) {
    const file = join(root, "topics", `${topic.slug}.html`);
    topic.sections = [];
    if (!existsSync(file)) {
      console.warn(`missing page: topics/${topic.slug}.html`);
      problems++;
      continue;
    }
    const html = readFileSync(file, "utf8");
    const ids = new Set();
    for (const [tag] of html.matchAll(/<section\b[^>]*>/g)) {
      const cls = attr(tag, "class") || "";
      if (!/\blesson\b/.test(cls)) continue;
      const id = attr(tag, "id");
      const title = attr(tag, "data-title");
      if (!id || !title) {
        console.warn(`${topic.slug}: lesson section without id/data-title: ${tag}`);
        problems++;
        continue;
      }
      if (ids.has(id)) {
        console.warn(`${topic.slug}: duplicate section id "${id}"`);
        problems++;
        continue;
      }
      ids.add(id);
      topic.sections.push({ id, title });
    }
    const lead = html.match(/<p class="lead">([\s\S]*?)<\/p>/);
    topic.lead = lead ? lead[1].replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim() : "";
    if (!topic.sections.length) {
      console.warn(`${topic.slug}: no lesson sections found`);
      problems++;
    }
  }
}

const out = `// Generated by scripts/build-manifest.mjs — do not edit by hand.\nwindow.MANIFEST = ${JSON.stringify(catalog, null, 1)};\n`;
writeFileSync(join(root, "assets/js/manifest.js"), out);
const total = catalog.exams.flatMap((e) => e.topics).reduce((n, t) => n + t.sections.length, 0);
console.log(`manifest written: ${catalog.exams.length} exams, ${total} sections, ${problems} problem(s)`);
process.exitCode = problems ? 1 : 0;
